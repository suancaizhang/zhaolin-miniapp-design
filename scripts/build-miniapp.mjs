import { access, cp, lstat, mkdir, mkdtemp, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(new URL('../miniapp/package.json', import.meta.url));
const packagePath = require.resolve('tdesign-miniprogram/package.json');
const packageRoot = dirname(packagePath);
const metadata = JSON.parse(await readFile(packagePath, 'utf8'));
if (metadata.version !== '1.17.0') {
  throw new Error(`Expected tdesign-miniprogram 1.17.0; installed ${metadata.version}. Install the locked workspace dependencies first.`);
}
const distribution = join(packageRoot, 'miniprogram_dist');
for (const component of ['button', 'tag', 'loading', 'empty']) {
  for (const extension of ['js', 'json', 'wxml', 'wxss']) {
    await access(join(distribution, component, `${component}.${extension}`));
  }
}
const licenseName = (await readdir(packageRoot)).find((name) => /^licen[cs]e(?:\.md|\.txt)?$/i.test(name));
if (!licenseName) throw new Error('Installed TDesign package is missing its license; refusing to vendor without it.');

// Only replace a directory generated by this command; never traverse user links.
const destination = join(root, 'miniapp', 'miniprogram_npm', 'tdesign-miniprogram');
const marker = '.zhaolin-generated';
const ownership = 'tdesign-miniprogram@1.17.0\n';
async function rejectLinks(path) {
  const info = await lstat(path);
  if (info.isSymbolicLink() || (!info.isDirectory() && !info.isFile())) throw new Error('Component path contains a link or non-regular file; replacement refused.');
  if (info.isDirectory()) {
    for (const name of await readdir(path)) await rejectLinks(join(path, name));
  }
}
await rejectLinks(distribution);
if (!(await lstat(join(packageRoot, licenseName))).isFile() || (await lstat(join(packageRoot, licenseName))).isSymbolicLink()) {
  throw new Error('Component license must be a regular file.');
}
for (const parent of [join(root, 'miniapp'), dirname(destination)]) {
  await mkdir(parent, { recursive: true });
  if ((await lstat(parent)).isSymbolicLink()) throw new Error('Component parent is a link; replacement refused.');
}
let exists = true;
try { await lstat(destination); } catch (error) {
  if (error.code !== 'ENOENT') throw error;
  exists = false;
}
if (exists) {
  await rejectLinks(destination);
  let previousOwner;
  try { previousOwner = await readFile(join(destination, marker), 'utf8'); }
  catch { throw new Error('Existing component directory has no generator ownership marker; replacement refused.'); }
  if (previousOwner !== ownership) throw new Error('Component generator ownership mismatch; replacement refused.');
}
const staging = await mkdtemp(join(dirname(destination), '.tdesign-stage-'));
const previous = `${staging}.previous`;
let staged = true;
let movedPrevious = false;
try {
  await cp(distribution, staging, { recursive: true });
  await cp(join(packageRoot, licenseName), join(staging, licenseName));
  await writeFile(join(staging, marker), ownership);
  await rejectLinks(staging);
  if (exists) {
    await rename(destination, previous);
    movedPrevious = true;
  }
  try {
    await rename(staging, destination);
    staged = false;
  } catch (error) {
    if (movedPrevious) {
      await rename(previous, destination);
      movedPrevious = false;
    }
    throw error;
  }
  if (movedPrevious) await rm(previous, { recursive: true });
} finally {
  if (staged) await rm(staging, { recursive: true });
}
// A complete, owned tree is now ready for the user's Developer Tools import.
console.log(`Vendored real tdesign-miniprogram ${metadata.version} distribution and ${licenseName} into miniapp/miniprogram_npm.`);
